"""Team 5 generator: the Rust comparison fixtures and edit sequences.

An idiomatic, std-only Rust crate with the SAME generic DAG shape as the B3
fixtures (D=20 W=4 spine DAG and the D=50 W=4 fan-in, K=2 user types):

  * every node is a free generic function bounded by one trait,
    `pub fn n018_0<T: Score>(x: &T) -> i64 { n019_0(x) + 1 }`; the leaf calls
    the trait method (`x.score()`); the root sums the W entry chains;
  * K user types are plain structs implementing `Score`; `main` calls `root`
    once per type and sums into an `f64` (so an `i64` and an `f64` root result
    are both legal, exactly like the B3 `main`);
  * no macros, no `dyn`, no `impl Trait` tricks.

Layouts (the Rust counterparts of the Moss ones):

  rust_dag_single_d20_w4_k02    ONE package, ONE crate (src/main.rs + `mod dag`
                                in src/dag.rs): the equivalent of the B3 single
                                package (DAG and `main` in the same crate)
  rust_dag_ws_d20_w4_k02        a workspace of two crates joined by a path
                                dependency (`dag_lib` holds the DAG and exports
                                `root`; `dag_app` defines the types and calls
                                it): the equivalent of B1 (lib + app)
  rust_fanin_single_d50_w4_k02  the fan-in shape in one crate

Edits (frozen patches; positions equal the B3 positions: the same leaf `n019_0`
/ `c049`). See README "Rust comparison (Team 5)" for what each one is and why:
  a  `let k = 1;` -> `let k = 2;`
  b  leaf `-> f64` and `let k = 0.5;`, and the signature `-> f64` / literal
     `+ 1.0` of EVERY function in the call cone (Rust has no return-type
     inference across functions, so the Moss one-line edit is a multi-line edit)
  c  the first two statements swapped
  d  comment text only
  e  one comment line inserted above the leaf (line shift)
  f  error path at the TOP node (n000_0 / e0, see probes/f_edit_probe.txt for why not the leaf):
     `+ 1` -> `+ "one"` (a type error: `i64 + &str`)
(b2 has no Rust counterpart: see README.)

Generated with fixed text only; the suite seed picks the per-type constants
(same policy as every other generator: an RNG stream derived from the suite
seed and the generator name).
"""
from __future__ import annotations

from pathlib import Path
import random
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ect_common as C  # noqa: E402
from edit_generators import scenario_row  # noqa: E402

DEPTH, WIDTH, TYPES = 20, 4, 2
FDEPTH, FWIDTH = 50, 4
KIND = "cargo"
FAMILY = "rust_edits"
SEQ_KIND = "rust_edit_sequence"

LOCK_HEADER = ("# This file is automatically @generated by Cargo.\n"
               "# It is not intended for manual editing.\nversion = 4\n\n")


def lock_single(name: str) -> str:
    return LOCK_HEADER + f'[[package]]\nname = "{name}"\nversion = "0.1.0"\n'


def lock_ws() -> str:
    return (LOCK_HEADER + '[[package]]\nname = "dag_app"\nversion = "0.1.0"\n'
            'dependencies = [\n "dag_lib",\n]\n\n'
            '[[package]]\nname = "dag_lib"\nversion = "0.1.0"\n')


def cargo_toml(name: str, dep: bool = False) -> str:
    s = f'[package]\nname = "{name}"\nversion = "0.1.0"\nedition = "2021"\n'
    if dep:
        s += '\n[dependencies]\ndag_lib = { path = "../lib" }\n'
    return s


# --- DAG source ------------------------------------------------------------

LEAF_COMMENT = "// leaf body"


def leaf_text(name: str, *, k: str = "1", swapped: bool = False, ret: str = "i64",
              cast: str = "r + k", comment: str = LEAF_COMMENT) -> str:
    body = (f"    let r = x.score();\n    let k = {k};\n" if swapped
            else f"    let k = {k};\n    let r = x.score();\n")
    return f"pub fn {name}<T: Score>(x: &T) -> {ret} {{\n    {comment}\n{body}    {cast}\n}}\n"


def inner_text(name: str, child: str, ret: str = "i64", one: str = "1") -> str:
    return f"pub fn {name}<T: Score>(x: &T) -> {ret} {{\n    {child}(x) + {one}\n}}\n"


def entry_text(name: str, child: str, i: int, ret: str = "i64", suffix: str = "") -> str:
    return f"pub fn {name}<T: Score>(x: &T) -> {ret} {{\n    {child}(x) + {i}{suffix}\n}}\n"


def root_text(terms: list[str], cone: frozenset | None = None) -> str:
    """Sum of the entry calls. In an f64 cone the entries outside the cone still
    return i64 and are widened with `as f64` (Rust has no implicit i64 -> f64)."""
    if cone is None or "root" not in cone:
        return "pub fn root<T: Score>(x: &T) -> i64 {\n    " + " + ".join(f"{t}(x)" for t in terms) + "\n}\n"
    return ("pub fn root<T: Score>(x: &T) -> f64 {\n    " +
            " + ".join(f"{t}(x)" if t in cone else f"{t}(x) as f64" for t in terms) + "\n}\n")


def dag_nodes(depth: int, width: int, cone: frozenset | None = None) -> list[tuple[str, str]]:
    """[(name, text)] leaves first; the same order as the Moss source. Names in
    `cone` get the f64 return type (edit b)."""
    cone = cone or frozenset()
    out = []
    for level in range(depth - 1, -1, -1):
        for i in range(width):
            name = f"n{level:03d}_{i}"
            f = name in cone
            if level == depth - 1:
                out.append((name, leaf_text(name, k="0.5", ret="f64", cast="r as f64 + k")
                            if f else leaf_text(name)))
            else:
                out.append((name, inner_text(name, f"n{level + 1:03d}_{i}",
                                             "f64" if f else "i64", "1.0" if f else "1")))
    out.append(("root", root_text([f"n000_{i}" for i in range(width)], cone or None)))
    return out


def fanin_nodes(depth: int, width: int, cone: frozenset | None = None) -> list[tuple[str, str]]:
    cone = cone or frozenset()
    out = []
    for level in range(depth - 1, -1, -1):
        name = f"c{level:03d}"
        f = name in cone
        if level == depth - 1:
            out.append((name, leaf_text(name, k="0.5", ret="f64", cast="r as f64 + k")
                        if f else leaf_text(name)))
        else:
            out.append((name, inner_text(name, f"c{level + 1:03d}", "f64" if f else "i64", "1.0" if f else "1")))
    for i in range(width):
        f = f"e{i}" in cone
        out.append((f"e{i}", entry_text(f"e{i}", "c000", i, "f64" if f else "i64", ".0" if f else "")))
    out.append(("root", root_text([f"e{i}" for i in range(width)], cone or None)))
    return out


TRAIT = "pub trait Score {\n    fn score(&self) -> i64;\n}\n"


def dag_file(nodes: list[tuple[str, str]], header: str) -> str:
    return header + TRAIT + "\n" + "\n".join(t for _, t in nodes)


def types_text(k: int, base: int) -> str:
    out = []
    for i in range(k):
        out.append(f"pub struct T{i:03d} {{\n    pub v: i64,\n}}\n\n"
                   f"impl Score for T{i:03d} {{\n    fn score(&self) -> i64 {{\n"
                   f"        self.v + {base + i}\n    }}\n}}\n")
    return "\n".join(out)


def main_text(k: int) -> str:
    calls = "".join(f"    total += root(&T{i:03d} {{ v: {i + 1} }}) as f64;\n" for i in range(k))
    return f"fn main() {{\n    let mut total = 0.0;\n{calls}    println!(\"{{}}\", total);\n}}\n"


def single_crate(root: Path, name: str, nodes, base: int, k: int) -> None:
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(cargo_toml(name))
    (root / "Cargo.lock").write_text(lock_single(name))
    (root / "src" / "dag.rs").write_text(dag_file(nodes, "// generated generic DAG: every node is generic over `Score`\n"))
    (root / "src" / "main.rs").write_text(
        "mod dag;\n\nuse dag::{root, Score};\n\n" + types_text(k, base) + "\n" + main_text(k))


def workspace(root: Path, nodes, base: int, k: int) -> None:
    (root / "lib" / "src").mkdir(parents=True)
    (root / "app" / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text('[workspace]\nmembers = ["lib", "app"]\nresolver = "2"\n')
    (root / "Cargo.lock").write_text(lock_ws())
    (root / "lib" / "Cargo.toml").write_text(cargo_toml("dag_lib"))
    (root / "app" / "Cargo.toml").write_text(cargo_toml("dag_app", dep=True))
    (root / "lib" / "src" / "lib.rs").write_text(dag_file(nodes, "// generated generic DAG library\n"))
    (root / "app" / "src" / "main.rs").write_text(
        "use dag_lib::{root, Score};\n\n" + types_text(k, base) + "\n" + main_text(k))


class RustDagGenerator(C.Generator):
    name = "rust_dag"
    version = "1.0.0"
    category = "rust_dag"

    # (id, layout, shape, depth, width, edit file relative to fixture, leaf, builder)
    SHAPES = (
        ("rust_dag_single_d20_w4_k02", "single", "dag", DEPTH, WIDTH, "crate/src/dag.rs", "n019_0", dag_nodes),
        ("rust_dag_ws_d20_w4_k02", "workspace", "dag", DEPTH, WIDTH, "ws/lib/src/lib.rs", "n019_0", dag_nodes),
        ("rust_fanin_single_d50_w4_k02", "single", "fanin", FDEPTH, FWIDTH, "crate/src/dag.rs", "c049", fanin_nodes),
    )

    def __init__(self):
        self.scenarios: list[dict] = []

    def generate(self, rng: random.Random, out_dir: Path) -> list[dict]:
        self.scenarios = []
        base = rng.randint(1, 9)
        rows = []
        for fid, layout, shape, depth, width, edit_file, leaf, builder in self.SHAPES:
            d = out_dir / "rust_dag" / fid
            nodes = builder(depth, width)
            if layout == "single":
                single_crate(d / "crate", "dag_single", nodes, base, TYPES)
                entry, packages = "crate", 1
            else:
                workspace(d / "ws", nodes, base, TYPES)
                entry, packages = "ws", 2
            n_nodes = len(nodes)
            rows.append({
                "id": fid, "path": f"rust_dag/{fid}", "kind": KIND, "entry": entry,
                "timeout_s": 300, "expected_status": "pass",
                "metadata": {"family": "rust_dag", "layout": layout, "shape": shape,
                             "depth": depth, "width": width, "types": TYPES, "nodes": n_nodes,
                             "packages": packages, "edit_leaf": leaf,
                             "moss_counterpart": ("b3_dag_d20_w4_k02" if shape == "dag"
                                                  else "b3_fanin_d50_w4_k02")}})
            base_leaf = leaf_text(leaf)
            cone_names = self._cone(nodes, leaf)
            cone = dict(builder(depth, width, frozenset(cone_names)))
            old_by = dict(nodes)
            edits = {
                "a": ("summary-unchanged body edit", "local", [dict(k="2")]),
                "b": ("return type i64 -> f64 through the call cone", "cone", None),
                "c": ("two first statements swapped", "local", [dict(swapped=True)]),
                "d": ("comment-only", "none", [dict(comment="// leaf body (reworded)")]),
                "e": ("one comment line inserted above the leaf (line shift)", "identity", "prefix"),
                "f": ("error path: `+ 1` -> `+ \"one\"` in the top node (i64 + &str)", "error", "break"),
            }
            for eid, (label, classification, change) in edits.items():
                if eid == "b":
                    # the cone is the leaf plus every function that transitively calls it
                    pe = [{"file": edit_file, "old": old_by[n], "new": cone[n]} for n in cone_names]
                elif change == "break":
                    node = "n000_0" if shape == "dag" else "e0"
                    tail = "+ 1\n" if shape == "dag" else "+ 0\n"
                    pe = [{"file": edit_file, "old": old_by[node],
                           "new": old_by[node].replace(tail, '+ "one"\n')}]
                    assert pe[0]["new"] != pe[0]["old"]
                elif change == "prefix":
                    pe = [{"file": edit_file, "old": base_leaf,
                           "new": "// inserted above the leaf\n" + base_leaf}]
                else:
                    pe = [{"file": edit_file, "old": base_leaf,
                           "new": leaf_text(leaf, **change[0])}]
                patch = C.make_patch(eid, d, pe)
                sid = f"rust_{'dag' if shape == 'dag' else 'fanin'}_{layout}_{eid}"
                expect_edit = "fail" if eid == "f" else "pass"
                self.scenarios.append(scenario_row({
                    "id": sid, "family": FAMILY, "fixture": fid, "kind": SEQ_KIND,
                    "description": f"{label} at leaf {leaf} of the {shape} ({layout} layout)",
                    "edited_function": leaf, "classification": classification,
                    "edit_count": len(pe), "patches": {eid: patch},
                    "steps": [
                        {"op": "check", "label": "first", "expect": "pass"},
                        {"op": "check", "label": "second", "expect": "pass"},
                        {"op": "apply", "patch": eid},
                        {"op": "check", "label": "edit", "expect": expect_edit,
                         **({"expect_exit": 101} if expect_edit == "fail" else {})},
                        {"op": "revert", "patch": eid},
                        {"op": "check", "label": "revert", "expect": "pass"}]}))
        # startup floor: a crate whose main only prints a literal (the B4 floor counterpart)
        d = out_dir / "rust_dag" / "rust_floor_single"
        (d / "crate" / "src").mkdir(parents=True)
        (d / "crate" / "Cargo.toml").write_text(cargo_toml("floor"))
        (d / "crate" / "Cargo.lock").write_text(lock_single("floor"))
        (d / "crate" / "src" / "main.rs").write_text('fn main() {\n    println!("0");\n}\n')
        rows.append({"id": "rust_floor_single", "path": "rust_dag/rust_floor_single", "kind": KIND,
                     "entry": "crate", "timeout_s": 300, "expected_status": "pass",
                     "metadata": {"family": "rust_floor", "layout": "single", "nodes": 0, "packages": 1,
                                  "note": "startup floor: a main that only prints a literal"}})
        patch = C.make_patch("edit", d, [{"file": "crate/src/main.rs", "old": '    println!("0");\n',
                                          "new": '    println!("1");\n'}])
        self.scenarios.append(scenario_row({
            "id": "rust_floor_edit", "family": FAMILY, "fixture": "rust_floor_single", "kind": SEQ_KIND,
            "description": "one-line literal edit in the floor crate", "edited_function": "main",
            "classification": "local", "edit_count": 1, "patches": {"edit": patch},
            "steps": [
                {"op": "check", "label": "first", "expect": "pass"},
                {"op": "check", "label": "second", "expect": "pass"},
                {"op": "apply", "patch": "edit"},
                {"op": "check", "label": "edit", "expect": "pass"},
                {"op": "revert", "patch": "edit"},
                {"op": "check", "label": "revert", "expect": "pass"}]}))
        return rows

    @staticmethod
    def _cone(nodes: list[tuple[str, str]], leaf: str) -> list[str]:
        """Names of `leaf` and every function that transitively calls it,
        computed from the generated TEXT (a call is `<name>(x)`), in source order."""
        names = [n for n, _ in nodes]
        text = dict(nodes)
        cone = {leaf}
        changed = True
        while changed:
            changed = False
            for n in names:
                if n not in cone and any(f"{c}(x)" in text[n] for c in cone):
                    cone.add(n)
                    changed = True
        return [n for n in names if n in cone]


RUST_GENERATORS = [RustDagGenerator()]
