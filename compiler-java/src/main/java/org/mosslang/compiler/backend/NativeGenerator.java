package org.mosslang.compiler.backend;

import org.mosslang.compiler.ast.*;
import java.util.List;

public class NativeGenerator {
    public static String generate(Program program, boolean debugBuild) {
        StringBuilder o = new StringBuilder();
        o.append("// Generated by Moss v0.1. Do not edit by hand.\n");
        o.append("// Synchronous domain calls enter compiler-planned handler-level 2PL.\n");
        o.append("#![allow(non_snake_case)]\n");
        o.append("#![allow(non_camel_case_types)]\n");
        o.append("#![allow(dead_code)]\n");
        o.append("#![allow(unused_imports)]\n");
        o.append("#![allow(unused_mut)]\n");
        o.append("#![allow(unused_variables)]\n");
        o.append("#![allow(unused_assignments)]\n\n");

        o.append("fn __moss_require_send<T: Send>() {}\n\n");
        o.append("#[inline(always)]\n");
        o.append("fn __moss_shl(value: i64, shift: i64) -> i64 {\n");
        o.append("    if shift < 0 || shift >= 64 { 0 } else { value.wrapping_shl(shift as u32) }\n");
        o.append("}\n\n");
        o.append("#[inline(always)]\n");
        o.append("fn __moss_shr(value: i64, shift: i64) -> i64 {\n");
        o.append("    if shift < 0 || shift >= 64 { if value < 0 { -1 } else { 0 } } else { value.wrapping_shr(shift as u32) }\n");
        o.append("}\n\n");

        o.append(MossRuntimeSupport.HANDLER_RUNTIME).append("\n");
        o.append(MossRuntimeSupport.STRING_RUNTIME).append("\n");
        o.append(MossRuntimeSupport.DISPLAY_RUNTIME).append("\n");

        // Enums
        for (EnumType e : program.enums) {
            o.append("#[derive(Clone, Debug)]\n");
            o.append("enum ").append(e.name).append(" {\n");
            for (EnumCase c : e.cases) {
                o.append("    ").append(c.name).append(",\n");
            }
            o.append("}\n\n");
        }

        // Objects
        for (ObjectType obj : program.objects) {
            o.append("#[derive(Clone, Debug)]\n");
            o.append("struct ").append(obj.name).append(" {\n");
            for (Field f : obj.fields) {
                o.append("    pub ").append(f.name).append(": ").append(rustType(f.type)).append(",\n");
            }
            o.append("}\n\n");
        }

        // Functions
        for (Function fn : program.functions) {
            o.append("fn ").append(fn.name).append("(");
            java.util.Set<String> declared = new java.util.HashSet<>();
            for (int i = 0; i < fn.params.size(); i++) {
                if (i > 0) o.append(", ");
                Param p = fn.params.get(i);
                o.append(p.name).append(": ").append(rustType(p.type));
                declared.add(p.name);
            }
            o.append(")");
            if (fn.returnType != null && !fn.returnType.isEmpty() && !fn.returnType.equals("unit")) {
                o.append(" -> ").append(rustType(fn.returnType));
            }
            o.append(" {\n");
            for (Stmt s : fn.body) {
                genStmt(o, s, "    ", declared);
            }
            if (fn.resultExpression != null) {
                o.append("    ").append(lowerExpr(fn.resultExpression)).append("\n");
            }
            o.append("}\n\n");
        }

        // Main
        if (program.main != null) {
            o.append("#[export_name = \"moss__main\"]\n");
            o.append("fn main() {\n");
            java.util.Set<String> declared = new java.util.HashSet<>();
            for (Stmt s : program.main.body) {
                genStmt(o, s, "    ", declared);
            }
            o.append("}\n");
        }

        return o.toString();
    }

    private static String rustType(String mossType) {
        if (mossType == null || mossType.isEmpty()) return "()";
        return switch (mossType) {
            case "int", "Int" -> "i64";
            case "float", "Float" -> "f64";
            case "bool", "Bool" -> "bool";
            case "string", "String" -> "MossStr";
            case "char", "Char" -> "char";
            case "unit" -> "()";
            default -> mossType;
        };
    }

    private static void genStmt(StringBuilder o, Stmt s, String indent, java.util.Set<String> declared) {
        if (s == null) return;
        switch (s.kind) {
            case Echo -> {
                o.append(indent).append("println!(\"{}\", ");
                if (!s.args.isEmpty()) {
                    o.append(lowerExpr(s.args.get(0)));
                } else {
                    o.append("\"\"");
                }
                o.append(");\n");
            }
            case Let -> {
                declared.add(s.a);
                o.append(indent).append("let ").append(s.a).append(" = ").append(lowerExpr(s.b)).append(";\n");
            }
            case Var -> {
                declared.add(s.a);
                o.append(indent).append("let mut ").append(s.a).append(" = ").append(lowerExpr(s.b)).append(";\n");
            }
            case Assign -> {
                if (declared.add(s.a)) {
                    o.append(indent).append("let mut ").append(s.a).append(" = ").append(lowerExpr(s.b)).append(";\n");
                } else {
                    o.append(indent).append(s.a).append(" = ").append(lowerExpr(s.b)).append(";\n");
                }
            }
            case Return -> {
                o.append(indent).append("return ");
                if (s.a != null && !s.a.isEmpty()) {
                    o.append(lowerExpr(s.a));
                }
                o.append(";\n");
            }
            case Raw -> {
                String t = s.text != null ? s.text.trim() : "";
                if (t.startsWith("echo ")) {
                    String arg = t.substring(5).trim();
                    o.append(indent).append("println!(\"{}\", ").append(lowerExpr(arg)).append(");\n");
                } else if (t.contains("=") && !t.contains("==")) {
                    int eq = t.indexOf('=');
                    String lhs = t.substring(0, eq).trim();
                    String rhs = t.substring(eq + 1).trim();
                    if (declared.add(lhs)) {
                        o.append(indent).append("let mut ").append(lhs).append(" = ").append(lowerExpr(rhs)).append(";\n");
                    } else {
                        o.append(indent).append(lhs).append(" = ").append(lowerExpr(rhs)).append(";\n");
                    }
                } else if (!t.isEmpty()) {
                    o.append(indent).append(lowerExpr(t)).append(";\n");
                }
            }
            default -> {
                String t = s.text != null ? s.text.trim() : "";
                if (!t.isEmpty()) {
                    o.append(indent).append(lowerExpr(t)).append(";\n");
                }
            }
        }
    }

    private static String lowerExpr(String expr) {
        if (expr == null) return "";
        expr = expr.trim();
        if (expr.startsWith("\"") && expr.endsWith("\"")) {
            return "MossStr::from(" + expr + ")";
        }
        return expr;
    }
}
